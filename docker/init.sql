CREATE TABLE teams (
  team_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL
);

CREATE TABLE roles (
  role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(50) NOT NULL
);

CREATE TABLE players (
  player_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(256)
);

CREATE TABLE games (
  game_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  played_at TIMESTAMP NOT NULL,
  approved BOOLEAN NOT NULL DEFAULT FALSE,
  winning_team INTEGER NOT NULL REFERENCES teams(team_id),
  player_count INTEGER,
  mafia_count INTEGER,
  mafia_kill_power INTEGER,
  day_count INTEGER,
  night_count INTEGER
);

CREATE TABLE game_participants (
  game_id BIGINT NOT NULL REFERENCES games(game_id),
  player_id INTEGER NOT NULL REFERENCES players(player_id),
  role_id INTEGER NOT NULL REFERENCES roles(role_id),
  team_id INTEGER NOT NULL REFERENCES teams(team_id),
  days_survived INTEGER,
  nights_survived INTEGER,
  successful_spy_checks INTEGER,
  spy_check_opportunities INTEGER,
  medic_self_saves INTEGER,
  successful_medic_saves INTEGER,
  medic_save_opportunities INTEGER,
  successful_assassin_shots INTEGER,
  assassin_shot_attempts INTEGER,
  PRIMARY KEY (game_id, player_id)
);

